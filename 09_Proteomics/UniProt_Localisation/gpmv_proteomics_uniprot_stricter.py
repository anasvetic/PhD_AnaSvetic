def read_csv(path: Path):
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        return reader.fieldnames or [], rows


def write_csv(path: Path, rows, fieldnames):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def normalized_text(*values):
    return " ; ".join(str(v or "") for v in values).lower()


def has_any(text, terms):
    return any(term.lower() in text for term in terms)


def strict_category_match(category, subcell, gocc):
    """
    Return True if a protein meets the stricter rule for a category.

    Extracellular / secreted is handled conservatively:
    "extracellular exosome" or "extracellular vesicle" alone do NOT count.
    """
    rule = STRICT_CATEGORY_TERMS[category]
    text = normalized_text(subcell, gocc)

    if category != "Extracellular / secreted":
        return has_any(text, rule["include"])

    # For extracellular/secreted, first remove exosome/vesicle phrases before
    # evaluating the explicit extracellular-region evidence. This prevents
    # "extracellular exosome" from matching merely because it contains the
    # word "extracellular".
    cleaned = text
    for phrase in rule["exclude_if_only"]:
        cleaned = cleaned.replace(phrase, " ")

    # "Secreted" from UniProt subcellular-location or genuine extracellular
    # region/space/fluid annotations remain valid.
    return has_any(cleaned, rule["include"])


def classify_row(row):
    subcell = row.get(COL_SUBCELL, "")
    gocc = row.get(COL_GOCC, "")

    labels = []
    for category in STRICT_CATEGORY_TERMS:
        if strict_category_match(category, subcell, gocc):
            labels.append(category)

    if not labels:
        labels = ["Other / no strict broad match"]

    return labels


def safe_bool_text(value):
    text = str(value or "").strip()
    return "Yes" if text else "No"


# ---------------------------------------------------------------------------
# FISHER'S EXACT TEST - STANDARD LIBRARY IMPLEMENTATION
# ---------------------------------------------------------------------------

def hypergeom_probability(x, row1, row2, col1):
    """
    Hypergeometric probability of x in the top-left cell, conditional on
    fixed margins.
    """
    total = row1 + row2
    col2 = total - col1

    if x < 0 or x > row1 or x > col1:
        return 0.0
    if row1 - x < 0 or row1 - x > col2:
        return 0.0

    numerator = math.comb(col1, x) * math.comb(col2, row1 - x)
    denominator = math.comb(total, row1)
    return numerator / denominator


def fisher_exact_two_sided(a, b, c, d):
    """
    Two-sided Fisher's exact test using the common probability-ordering
    definition: sum probabilities of all feasible tables with probability
    <= that of the observed table.
    """
    row1 = a + b
    row2 = c + d
    col1 = a + c
    total = row1 + row2

    observed_p = hypergeom_probability(a, row1, row2, col1)

    lower = max(0, row1 - (total - col1))
    upper = min(row1, col1)

    pvalue = 0.0
    tolerance = observed_p * 1e-12 + 1e-16

    for x in range(lower, upper + 1):
        p = hypergeom_probability(x, row1, row2, col1)
        if p <= observed_p + tolerance:
            pvalue += p

    pvalue = min(1.0, pvalue)

    if b == 0 or c == 0:
        if a * d == 0:
            odds_ratio = math.nan
        else:
            odds_ratio = math.inf
    else:
        odds_ratio = (a * d) / (b * c)

    return odds_ratio, pvalue


def benjamini_hochberg(pvalues):
    """
    Benjamini-Hochberg FDR correction.
    Returns adjusted p-values in the original order.
    """
    m = len(pvalues)
    indexed = sorted(enumerate(pvalues), key=lambda x: x[1])

    adjusted_sorted = [0.0] * m
    previous = 1.0

    # Work backwards to enforce monotonicity.
    for reverse_rank, (original_index, p) in enumerate(reversed(indexed), start=1):
        rank = m - reverse_rank + 1
        q = min(previous, p * m / rank, 1.0)
        adjusted_sorted[original_index] = q
        previous = q

    return adjusted_sorted


def format_or(value):
    if isinstance(value, float) and math.isnan(value):
        return "NA"
    if value == math.inf:
        return "inf"
    return f"{value:.6g}"


def category_summary(annotated_rows):
    enriched = [r for r in annotated_rows if r.get(COL_GROUP) == "GPMV-enriched"]
    depleted = [r for r in annotated_rows if r.get(COL_GROUP) == "GPMV-depleted"]

    if not enriched or not depleted:
        raise ValueError(
            "Input must contain both 'GPMV-enriched' and 'GPMV-depleted' "
            "values in the Differential_group column."
        )

    categories = list(STRICT_CATEGORY_TERMS) + ["Other / no strict broad match"]

    output = []
    raw_pvalues = []

    for category in categories:
        def belongs(row):
            labels = {
                x.strip()
                for x in row.get("Strict_localization_categories", "").split(";")
                if x.strip()
            }
            return category in labels

        a = sum(belongs(r) for r in enriched)
        c = sum(belongs(r) for r in depleted)
        b = len(enriched) - a
        d = len(depleted) - c

        enriched_pct = 100.0 * a / len(enriched)
        depleted_pct = 100.0 * c / len(depleted)

        odds_ratio, pvalue = fisher_exact_two_sided(a, b, c, d)
        raw_pvalues.append(pvalue)

        if enriched_pct > depleted_pct:
            direction = "Higher representation in GPMV-enriched"
        elif depleted_pct > enriched_pct:
            direction = "Higher representation in GPMV-depleted"
        else:
            direction = "Equal representation"

        output.append({
            "Category": category,
            "GPMV_enriched_count": a,
            "GPMV_enriched_total": len(enriched),
            "GPMV_enriched_percent": enriched_pct,
            "GPMV_depleted_count": c,
            "GPMV_depleted_total": len(depleted),
            "GPMV_depleted_percent": depleted_pct,
            "Odds_ratio_enriched_vs_depleted": format_or(odds_ratio),
            "Fisher_exact_p": pvalue,
            "Direction": direction,
        })

    adjusted = benjamini_hochberg(raw_pvalues)

    for row, q in zip(output, adjusted):
        row["BH_FDR_q"] = q
        row["FDR_significant_q_lt_0.05"] = "Yes" if q < 0.05 else "No"

    return output


def make_plot(summary, output_path):
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib is not installed; CSV outputs were created but PNG was skipped.")
        return

    categories = [r["Category"] for r in summary]
    enriched = [float(r["GPMV_enriched_percent"]) for r in summary]
    depleted = [float(r["GPMV_depleted_percent"]) for r in summary]

    y = list(range(len(categories)))
    height = 0.38

    fig_height = max(6.5, 0.62 * len(categories))
    fig, ax = plt.subplots(figsize=(11, fig_height))

    ax.barh(
        [v - height / 2 for v in y],
        enriched,
        height=height,
        label="GPMV-enriched",
    )
    ax.barh(
        [v + height / 2 for v in y],
        depleted,
        height=height,
        label="GPMV-depleted",
    )

    ax.set_yticks(y)
    ax.set_yticklabels(categories)
    ax.invert_yaxis()
    ax.set_xlabel("Proteins in differential-abundance group (%)")
    ax.set_title("Stricter UniProt localization analysis of differentially abundant proteins")
    ax.legend()

    # Mark FDR-significant category comparisons with an asterisk at the right.
    max_value = max(enriched + depleted) if (enriched + depleted) else 1
    for i, row in enumerate(summary):
        if row["FDR_significant_q_lt_0.05"] == "Yes":
            ax.text(
                max(enriched[i], depleted[i]) + max_value * 0.015,
                i,
                "*",
                va="center",
                fontsize=14,
            )

    ax.text(
        0,
        -0.13,
        "Categories are non-mutually-exclusive. * Fisher's exact test, BH-FDR q < 0.05.",
        transform=ax.transAxes,
        fontsize=9,
    )

    fig.tight_layout()
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def write_readme(path, n_total, n_enriched, n_depleted):
    methods_text = f"""GPMV STRICTER UNIPROT LOCALIZATION ANALYSIS
================================================

Input:
- UniProt-annotated significant proteins generated by the main QC pipeline.

Proteins analysed:
- Total significant proteins: {n_total}
- GPMV-enriched: {n_enriched}
- GPMV-depleted: {n_depleted}

Classification strategy:
- UniProt subcellular-location annotations and GO Cellular Component terms were
  used to assign broad localization categories.
- Categories were non-mutually-exclusive because proteins may have multiple
  bona fide subcellular localizations.
- Plasma membrane / cell surface required explicit cell-membrane,
  plasma-membrane or cell-surface annotation.
- Extracellular / secreted required explicit 'Secreted' or extracellular
  region/space/fluid evidence.
- 'Extracellular exosome' or 'extracellular vesicle' annotations alone were
  NOT considered sufficient to classify a protein as extracellular/secreted.
- Extracellular matrix was retained as a separate category.
- Other categories were assigned using explicit UniProt/GO localization terms
  for cytoskeleton/cortex, cytosol/cytoplasm, nucleus/chromatin, mitochondria,
  ER/Golgi, intracellular endosome/lysosome/vesicle compartments, and ribosome.

Statistical comparison:
- Each category was analysed independently because categories were
  non-mutually-exclusive.
- A two-sided Fisher's exact test compared the proportion of proteins assigned
  to each category in the GPMV-enriched and GPMV-depleted groups.
- P-values were corrected across tested localization categories using the
  Benjamini-Hochberg false-discovery-rate procedure.
- q < 0.05 was considered statistically significant for the category-level
  enriched-vs-depleted comparison.

Interpretation:
- This analysis tests differential REPRESENTATION of broad localization
  annotations between the enriched and depleted protein sets.
- It is descriptive/localization-based and should not be described as a formal
  Gene Ontology enrichment analysis.
- A formal GO enrichment analysis would require the complete QC-passed
  quantitatively analysed protein set as the experimental background.
"""
    path.write_text(methods_text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(
        description="Apply stricter UniProt localization rules and compare GPMV-enriched vs depleted proteins."
    )
    parser.add_argument(
        "annotated_csv",
        help="Path to 06_significant_proteins_UniProt_annotated.csv",
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help=(
            "Optional output folder. By default, a folder named "
            "'GPMV_stricter_localization_results' is created next to the input CSV."
        ),
    )
    args = parser.parse_args()

    input_path = Path(args.annotated_csv).expanduser().resolve()
    if not input_path.exists():
        raise FileNotFoundError(input_path)

    output_dir = (
        Path(args.output_dir).expanduser().resolve()
        if args.output_dir
        else input_path.parent / "GPMV_stricter_localization_results"
    )
    output_dir.mkdir(parents=True, exist_ok=True)

    headers, rows = read_csv(input_path)

    required = [COL_GROUP, COL_ACCESSION, COL_SUBCELL, COL_GOCC]
    missing = [c for c in required if c not in headers]
    if missing:
        raise KeyError(
            "Required columns are missing from the input CSV: "
            + ", ".join(missing)
        )

    valid_groups = {"GPMV-enriched", "GPMV-depleted"}
    rows = [r for r in rows if r.get(COL_GROUP) in valid_groups]

    if not rows:
        raise ValueError("No GPMV-enriched/depleted proteins found in the input file.")

    # Apply stricter multi-label classification.
    annotated = []
    for row in rows:
        out = dict(row)
        labels = classify_row(row)

        out["Strict_localization_categories"] = "; ".join(labels)
        out["Strict_plasma_membrane_cell_surface"] = (
            "Yes" if "Plasma membrane / cell surface" in labels else "No"
        )
        out["Strict_extracellular_secreted"] = (
            "Yes" if "Extracellular / secreted" in labels else "No"
        )
        out["Has_UniProt_transmembrane_annotation"] = safe_bool_text(row.get(COL_TM, ""))
        out["Has_UniProt_signal_peptide_annotation"] = safe_bool_text(row.get(COL_SIGNAL, ""))

        annotated.append(out)

    extra_fields = [
        "Strict_localization_categories",
        "Strict_plasma_membrane_cell_surface",
        "Strict_extracellular_secreted",
        "Has_UniProt_transmembrane_annotation",
        "Has_UniProt_signal_peptide_annotation",
    ]

    write_csv(
        output_dir / "01_stricter_localization_annotated.csv",
        annotated,
        headers + extra_fields,
    )

    summary = category_summary(annotated)

    summary_fields = [
        "Category",
        "GPMV_enriched_count",
        "GPMV_enriched_total",
        "GPMV_enriched_percent",
        "GPMV_depleted_count",
        "GPMV_depleted_total",
        "GPMV_depleted_percent",
        "Odds_ratio_enriched_vs_depleted",
        "Fisher_exact_p",
        "BH_FDR_q",
        "FDR_significant_q_lt_0.05",
        "Direction",
    ]

    write_csv(
        output_dir / "02_stricter_localization_summary_statistics.csv",
        summary,
        summary_fields,
    )

    make_plot(
        summary,
        output_dir / "03_stricter_localization_enriched_vs_depleted.png",
    )

    n_enriched = sum(r.get(COL_GROUP) == "GPMV-enriched" for r in annotated)
    n_depleted = sum(r.get(COL_GROUP) == "GPMV-depleted" for r in annotated)

    write_readme(
        output_dir / "README_stricter_analysis.txt",
        len(annotated),
        n_enriched,
        n_depleted,
    )

    print("\nSTRICTER LOCALIZATION ANALYSIS COMPLETE")
    print("-" * 55)
    print(f"Proteins analysed: {len(annotated)}")
    print(f"GPMV-enriched:     {n_enriched}")
    print(f"GPMV-depleted:     {n_depleted}")
    print(f"Results folder:    {output_dir}")
    print("\nMain statistical output:")
    print(output_dir / "02_stricter_localization_summary_statistics.csv")


if __name__ == "__main__":
    main()