#!/usr/bin/env python3
"""
GPMV proteomics - stricter UniProt localization analysis
========================================================

This script is a SECOND-STAGE analysis for the file generated by the main
GPMV proteomics pipeline:

    06_significant_proteins_UniProt_annotated.csv

It deliberately DOES NOT re-query UniProt. Instead, it uses the raw UniProt
subcellular-location and GO Cellular Component annotations already stored in
that file, applies stricter and explicitly documented localization rules, and
compares GPMV-enriched vs GPMV-depleted proteins.

Why a stricter second-stage analysis?
-------------------------------------
The first broad classifier was intentionally sensitive and could count proteins
as "extracellular / secreted" solely because of annotations such as
"extracellular exosome". That can inflate extracellular classification.

This stricter classifier:
- requires explicit Cell membrane / plasma-membrane / cell-surface evidence
  for the plasma-membrane category;
- requires explicit Secreted or extracellular-region/space evidence for the
  extracellular/secreted category;
- DOES NOT classify a protein as extracellular/secreted solely because it is
  annotated to an extracellular exosome/vesicle;
- keeps categories NON-MUTUALLY-EXCLUSIVE, because proteins can have multiple
  bona fide subcellular localizations;
- calculates a two-sided Fisher's exact test for each localization category;
- corrects category-wise p-values using Benjamini-Hochberg FDR.

Input
-----
The UniProt-annotated CSV produced by the main pipeline.

Example
-------
python gpmv_proteomics_uniprot_stricter.py \
    "C:\\path\\to\\06_significant_proteins_UniProt_annotated.csv"

Output
------
By default, a folder named:

    GPMV_stricter_localization_results

is created next to the input CSV.

Outputs include:
- 01_stricter_localization_annotated.csv
- 02_stricter_localization_summary_statistics.csv
- 03_stricter_localization_enriched_vs_depleted.png
- README_stricter_analysis.txt

Dependencies
------------
- Python standard library for classification + statistics
- matplotlib only for the PNG graph (optional)

Statistical note
----------------
For each non-mutually-exclusive category, the script builds a 2x2 table:

                    In category    Not in category
    GPMV-enriched       a                b
    GPMV-depleted       c                d

A two-sided Fisher's exact test compares category representation in enriched
and depleted proteins. P-values are adjusted across all tested localization
categories using Benjamini-Hochberg FDR.

This is a descriptive category-level comparison. It is not a replacement for
a formal Gene Ontology enrichment analysis using the full quantified proteome
as the experimental background.
"""

